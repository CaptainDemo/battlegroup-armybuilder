import { expect, test } from '@playwright/test';

test('shows unit rules and independently toggles a deduplicated print appendix', async ({page}) => {
  await page.goto('/?debug=1');
  await page.getByRole('button',{name:'Create the 398 Points / 23 BR example'}).click();
  await page.locator('.purchase-card').first().click();
  const composition=page.getByRole('region',{name:'Current composition'});
  const formationRules = composition.locator('[data-composition-path="[]"] > .composition-line .composition-rule');
  await expect(formationRules.getByText('Senior Officer', { exact: true })).toBeVisible();
  await expect(composition).not.toContainText('reroll one Orders die');
  await expect(page.locator('.purchase-card').first().locator('.rule-tag').getByText('Senior Officer', { exact: true })).toBeVisible();
  const selectedRules = page.locator('details:has(> summary:text-is("Unit data")) + details.special-rule-cards');
  const ruleText = selectedRules.getByText(/reroll one Orders die/);
  await expect(ruleText).toBeHidden();
  await selectedRules.locator('summary').click();
  await expect(ruleText).toBeVisible();
  await expect(selectedRules).toContainText('Battlegroup Rulebook');
  await expect(selectedRules.getByRole('heading', { name: 'Scout', exact: true })).toHaveCount(0);
  await page.getByRole('button',{name:'Print / PDF',exact:true}).click();
  await expect(page.locator('.special-rules-appendix')).toHaveCount(0);
  const toggle=page.getByRole('checkbox',{name:'Include special rule texts'});
  await toggle.check();
  const appendix=page.locator('.special-rules-appendix');
  await expect(appendix.getByRole('heading',{name:'Senior Officer',exact:true})).toHaveCount(1);
  await expect(appendix).toContainText('reroll one Orders die');
  await expect(appendix).toContainText('Scout');
  await expect(appendix).not.toContainText('Rule text has not been added');
  await expect(appendix).not.toContainText('max-per-parent');
  await page.emulateMedia({media:'print'});
  await expect(appendix).toBeVisible();
  await page.emulateMedia({media:'screen'});
  await toggle.uncheck();
  await expect(appendix).toHaveCount(0);
});
